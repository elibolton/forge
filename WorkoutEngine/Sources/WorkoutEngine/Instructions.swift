import Foundation

/// How to perform an exercise: a few short cues and the most common mistake.
public struct ExerciseGuide: Hashable, Sendable {
    public var steps: [String]
    public var mistake: String?

    public init(steps: [String], mistake: String? = nil) {
        self.steps = steps; self.mistake = mistake
    }
}

public enum Instructions {
